def _claim_image(document: int, page: int) -> ImageReader:
    image = Image.new("RGB", (720, 100), "white")
    draw = ImageDraw.Draw(image)
    draw.rectangle((2, 2, 718, 98), outline="black", width=2)
    draw.text((20, 35), f"Visual claim D{document:02d} P{page:02d}", fill="black")
    buffer = BytesIO()
    image.save(buffer, format="PNG")
    buffer.seek(0)
    return ImageReader(buffer)


def generate_complex_pdf(document: int, pages: int = 10) -> bytes:
    buffer = BytesIO()
    canvas = Canvas(buffer, pagesize=A4, pageCompression=1, invariant=1)
    width, height = A4
    for page in range(1, pages + 1):
        canvas.setFont("Helvetica-Bold", 15)
        canvas.drawString(42, height - 45, f"Synthetic compliance document {document:02d}")
        canvas.setFont("Helvetica", 9)
        canvas.drawRightString(width - 42, height - 45, f"Page {page}/{pages}")
        canvas.setFont("Helvetica-Bold", 11)
        canvas.drawString(42, height - 75, f"Section {page}. Marketing evidence")
        canvas.setFont("Helvetica", 9)
        left = [
            f"Claim {document}-{page} must be truthful and evidence based.",
            "The original amount, unit, channel and market must be preserved.",
            "This synthetic page is for parser load testing, not legal truth.",
        ]
        right = [
            "A reviewer must compare the claim with the cited official source.",
            "Automatic publication and automatic legal approval are disabled.",
            f"Document marker: D{document:02d}-P{page:02d}.",
        ]
        for index, line in enumerate(left):
            canvas.drawString(42, height - 100 - index * 15, line)
        for index, line in enumerate(right):
            canvas.drawString(width / 2 + 15, height - 100 - index * 15, line)

        top = height - 180
        columns = (42, 165, 310, 440, width - 42)
        rows = (top, top - 22, top - 44, top - 66, top - 88)
        for x in columns:
            canvas.line(x, rows[-1], x, rows[0])
        for y in rows:
            canvas.line(columns[0], y, columns[-1], y)
        canvas.setFont("Helvetica-Bold", 8)
        canvas.drawString(47, top - 15, "Market")
        canvas.drawString(170, top - 15, "Claim group")
        canvas.drawString(315, top - 15, "Evidence")
        canvas.drawString(445, top - 15, "Decision")
        canvas.setFont("Helvetica", 8)
        for row, market in enumerate(("CN", "US", "EU"), start=1):
            y = top - 15 - row * 22
            canvas.drawString(47, y, market)
            canvas.drawString(170, y, f"D{document:02d}-P{page:02d}-R{row}")
            canvas.drawString(315, y, "official source")
            canvas.drawString(445, y, "human review")
        canvas.drawImage(
            _claim_image(document, page), 42, height - 385,
            width=width - 84, height=70, preserveAspectRatio=True,
        )
        canvas.setFont("Helvetica", 8)
        canvas.drawString(42, 30, "Synthetic benchmark - generated by PolicyGuard AI")
        canvas.showPage()
    canvas.save()
    return buffer.getvalue()


def run_synthetic_pdf_benchmark(root: Path, documents: int = 20, pages: int = 10) -> dict:
    target = root / "data/evaluation/pdf/synthetic-v1"
    target.mkdir(parents=True, exist_ok=True)
    parser = PdfPlumberLayoutParser()
    results = []
    latencies = []
    for document in range(1, documents + 1):
        content = generate_complex_pdf(document, pages)
        path = target / f"synthetic-complex-{document:02d}.pdf"
        path.write_bytes(content)
        started = perf_counter()
        parsed = parser.parse(content, path.name)
        latency = (perf_counter() - started) * 1000
        latencies.append(latency)
        text = "\n".join(block.text for block in parsed.blocks)
        expected_markers = [f"D{document:02d}-P{page:02d}" for page in range(1, pages + 1)]
        results.append({
            "document_id": f"synthetic-complex-{document:02d}",
            "pages": pages,
            "bytes": len(content),
            "sha256": sha256(content).hexdigest(),
            "parsed_blocks": len(parsed.blocks),
            "marker_recall": round(
                sum(marker in text for marker in expected_markers) / len(expected_markers), 4
            ),
            "latency_ms": round(latency, 3),
        })
    report = {
        "dataset": "synthetic-complex-pdf-20x10-v1",
        "data_type": "programmatically_generated_not_real_regulation",
        "document_count": documents,
        "page_count": documents * pages,
        "features": ["two_columns", "multi_row_table", "embedded_image", "page_markers"],
        "mean_marker_recall": round(mean(item["marker_recall"] for item in results), 4),
        "mean_document_latency_ms": round(mean(latencies), 3),
        "p95_document_latency_ms": percentile(latencies, 0.95),
        "mean_page_latency_ms": round(sum(latencies) / (documents * pages), 3),
        "documents": results,
        "limitations": (
            "Engineering load/layout benchmark only; real PDF accuracy remains separately measured."
        ),
    }
    output = root / "data/benchmarks/synthetic-pdf-scale-v1.json"
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return report
